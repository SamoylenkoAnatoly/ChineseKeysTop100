          if (version !== animVersion) return;
          if (t0 === null) t0 = ts;
          var t = Math.min((ts - t0) / dur, 1);
          var ease = t < 0.5 ? 2 * t * t : 1 - Math.pow(-2 * t + 2, 2) / 2;
