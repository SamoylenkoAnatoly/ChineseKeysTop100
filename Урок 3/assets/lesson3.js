    function probeInto(box, ch, py, mean) {
      if (!box) return;
      var token = (box._picToken = (box._picToken || 0) + 1);
      var sources = ["img/" + ch + ".jpg", "img/" + ch + "1.jpg", "img/" + ch + ".png", "img/" + ch + "1.png", "img/" + ch + ".svg", "img/" + ch + "1.svg"];
      function attempt(i) {
        if (token !== box._picToken) return;
        var probe = new Image();
        probe.onload = function () {
          if (token !== box._picToken) return;
          var img = box.querySelector("img");
          if (!img) {
            img = document.createElement("img");
            box.appendChild(img);
          }
          img.alt = "Картинка: " + ch + " " + (py || "") + (mean ? " («" + mean + "»)" : "");
          img.src = sources[i];
        };
        probe.onerror = function () {
          if (token !== box._picToken) return;
          if (i + 1 < sources.length) attempt(i + 1);
          else {
            var img = box.querySelector("img");
            if (img) img.remove();
          }
        };
        probe.src = sources[i];
      }
      attempt(0);
    }

